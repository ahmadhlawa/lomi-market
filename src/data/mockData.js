export const getTrackingSteps = (status = 'on_the_way') => {
  const steps = [
    { key: 'placed', en: 'Order placed', ar: 'تم إرسال الطلب' },
    { key: 'preparing', en: 'Preparing', ar: 'جاري التجهيز' },
    { key: 'picked_up', en: 'Picked up', ar: 'تم الاستلام' },
    { key: 'on_the_way', en: 'On the way', ar: 'في الطريق' },
    { key: 'delivered', en: 'Delivered', ar: 'تم التوصيل' },
  ];
  const currentIndex = Math.max(0, steps.findIndex((step) => step.key === status));
  return steps.map((step, index) => ({
    ...step,
    state: index < currentIndex ? 'done' : index === currentIndex ? 'active' : 'pending',
  }));
};

